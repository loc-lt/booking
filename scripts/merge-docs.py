#!/usr/bin/env python3
"""Regenerate README.md as a single merged copy of docs/. docs/ stays the source
of truth; re-run this (CI does, in the docs_readme check job) after any doc change.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent

# (path relative to repo root, group label), in the same order as CLAUDE.md's
# "Where to find things" table.
DOCS = [
    ("docs/product.md", "Concept & business"),
    ("docs/demo-plan.md", "Concept & business"),
    ("docs/glossary.md", "Concept & business"),
    ("docs/architecture.md", "Architecture"),
    ("docs/core-boundaries.md", "Architecture"),
    ("docs/domain/booking.md", "Domain"),
    ("docs/domain/rules.md", "Domain"),
    ("docs/domain/configuration.md", "Domain"),
    ("docs/domain/events.md", "Domain"),
    ("docs/api.md", "Engineering guides"),
    ("docs/frontend.md", "Engineering guides"),
    ("docs/backend.md", "Engineering guides"),
    ("docs/analytics.md", "Engineering guides"),
    ("docs/operations.md", "Engineering guides"),
    ("docs/decisions.md", "Project"),
]

GROUP_ORDER = ["Concept & business", "Architecture", "Domain", "Engineering guides", "Project"]


def slugify(title):
    s = title.lower()
    s = re.sub(r"[^a-z0-9\s-]", "", s)
    return re.sub(r"\s+", "-", s.strip())


def bump_headings(text):
    out = []
    in_fence = False
    for line in text.split("\n"):
        if line.strip().startswith("```"):
            in_fence = not in_fence
            out.append(line)
            continue
        if not in_fence and re.match(r"^#{1,5}\s", line):
            out.append("#" + line)
        else:
            out.append(line)
    return "\n".join(out)


def main():
    titles = {}
    slug_by_filename = {}
    for path, _ in DOCS:
        first_line = (REPO / path).read_text().splitlines()[0]
        title = first_line.lstrip("#").strip()
        titles[path] = title
        slug_by_filename[Path(path).name] = slugify(title)

    def rewrite_links(text, depth):
        def repl(m):
            label, target = m.group(1), m.group(2)
            if target.startswith(("http://", "https://", "#", "mailto:")):
                return m.group(0)
            base = target.split("/")[-1]
            if target.endswith(".md") and base in slug_by_filename:
                return f"[{label}](#{slug_by_filename[base]})"
            if target == "../CLAUDE.md":
                return f"[{label}](CLAUDE.md)"
            if target == "domain/":
                return f"[{label}](#{slug_by_filename['booking.md']})"
            # example/data files: resolve relative to the source file's own directory
            if target.startswith("../"):
                resolved = "docs/" + target[len("../"):]
            elif depth == 0:
                resolved = "docs/" + target
            else:
                resolved = "docs/domain/" + target
            return f"[{label}]({resolved})"

        return re.sub(r"\[([^\]]+)\]\(([^)]+)\)", repl, text)

    sections = []
    toc_by_group = {}
    for path, group in DOCS:
        raw = (REPO / path).read_text()
        depth = path.count("/") - 1  # docs/x.md -> 0, docs/domain/x.md -> 1
        raw = rewrite_links(raw, depth)
        bumped = bump_headings(raw.rstrip() + "\n")
        sections.append(f"<!-- source: {path} -->\n\n{bumped}")
        toc_by_group.setdefault(group, []).append((titles[path], slugify(titles[path])))

    toc_lines = []
    for group in GROUP_ORDER:
        toc_lines.append(f"- **{group}**")
        for title, anchor in toc_by_group[group]:
            toc_lines.append(f"  - [{title}](#{anchor})")

    header = (
        "# Booking Core — Documentation\n\n"
        "One merged, read-top-to-bottom copy of everything under [`docs/`](docs/), for anyone "
        "who wants the whole picture without opening fifteen files. **`docs/` stays the source "
        "of truth** — this file is generated by `scripts/merge-docs.py` in CI; never hand-edit "
        "it.\n\n"
        "## Table of contents\n\n" + "\n".join(toc_lines) + "\n"
    )

    body = "\n\n---\n\n".join(sections)
    (REPO / "README.md").write_text(header + "\n---\n\n" + body + "\n")


if __name__ == "__main__":
    main()
